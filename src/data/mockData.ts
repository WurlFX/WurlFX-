export function generateInitialCandles(basePrice: number, count: number = 60, intervalMinutes: number = 5): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * 0.985;
  const now = Date.now();
  const stepMs = intervalMinutes * 60 * 1000;

  for (let i = count; i >= 0; i--) {
    const time = now - i * stepMs;
    const volatility = basePrice * 0.0025;
    const change = (Math.random() - 0.49) * volatility;
    const open = currentPrice;
    const close = open + change;
    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    const volume = Math.floor(Math.random() * 450 + 50);

    candles.push({
      time,
      open,
      high,
      low,
      close,
      volume,
    });
    currentPrice = close;
  }
  return candles;
}

